#!/usr/bin/env node
// Inlines the Lucide icons Rosetta uses into src/components/ui/icons.ts
// (style.md §9), so nothing the UI draws touches the network.
//
//   npm run icons
//
// Reads the pinned lucide-static devDependency. Every <Icon name="…"> in
// src/ is picked up; names chosen at runtime go in EXTRA.

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('lucide-static/package.json'));
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;

const EXTRA = [
  'book-open', 'file-text', 'file-type', 'file-code', 'file', 'globe', 'info', 'circle-check', 'triangle-alert', 'bookmark', 'bookmark-check', 'highlighter', 'image',
];

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : /\.(svelte|ts)$/.test(name) ? [path] : [];
  });
}

const names = new Set(EXTRA);
for (const file of walk(join(root, 'src'))) {
  const source = readFileSync(file, 'utf8');
  for (const m of source.matchAll(/<Icon\s+name="([a-z0-9-]+)"/g)) names.add(m[1]);
  for (const m of source.matchAll(/\bicon:\s*'([a-z0-9-]+)'/g)) names.add(m[1]);
  for (const m of source.matchAll(/\bicon="([a-z0-9-]+)"/g)) names.add(m[1]);
  for (const m of source.matchAll(/<Icon\s+name=\{[^}]*\}/g)) for (const q of m[0].matchAll(/'([a-z0-9-]+)'/g)) names.add(q[1]);
}

const entries = [...names].sort().map((name) => {
  const svg = readFileSync(join(pkgDir, 'icons', `${name}.svg`), 'utf8');
  const inner = svg
    .slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
    .replace(/\s*\n\s*/g, '')
    .replace(/\s+\/>/g, '/>');
  return `  '${name}': '${inner}',`;
});

const out = `// Generated by scripts/build-icons.mjs from lucide-static ${version} (ISC licence). Do not edit.

export const ICONS = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICONS;
`;
writeFileSync(join(root, 'src/components/ui/icons.ts'), out);
console.log(`Wrote src/components/ui/icons.ts: ${names.size} icons from lucide-static ${version}.`);
